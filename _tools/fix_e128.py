def main():
    rows = {}
    with io.open('_work/subtitles/TWN_E128_cd3_de.csv', encoding='latin1') as f:
        for ln in f:
            q = ln.rstrip('\r\n').split(';')
            if len(q) >= 6 and q[0].isdigit():
                rows[int(q[0])] = q[4]
    bad = 0
    for uid, de in sorted(FIX.items()):
        if uid not in rows:
            print('MISSING uid=%d' % uid)
            bad += 1
            continue
        if len(de) > len(rows[uid]):
            print('LEN uid=%d de=%d en=%d DE=%r EN=%r'
                  % (uid, len(de), len(rows[uid]), de, rows[uid]))
            bad += 1
    print('checked=%d bad=%d' % (len(FIX), bad))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='latin1')
    main()
