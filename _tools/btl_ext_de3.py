def esc(t):
    return t.replace('\\', '\\\\').replace('\n', '\\n')


FIX.pop('Right Arm ParalyzedX', None)

FILES = ['BTL_A3_FNT', 'BTL_A32_FNT', 'BTL_A53_FNT', 'BTL_A5_2_PRG',
         'BTL_A7_FNT', 'BTL_A72_FNT', 'BTL_B2_FNT', 'BTL_B53_FNT',
         'BTL_B5_2_PRG', 'BTL_B6_FNT', 'BTL_B62_FNT', 'BTL_C22_FNT',
         'BTL_C4_FNT', 'BTL_C5_FNT', 'BTL_C8_FNT', 'BTL_C82_FNT',
         'BTL_D2_FNT', 'BTL_D22_FNT', 'BTL_D4_FNT', 'BTL_D5_FNT']

total = over = skip = 0
for name in FILES:
    enp = '_work/menu_de/%s_en.csv' % name
    outp = '_work/menu_de/%s_de2b.csv' % name
    rows = []
    rd = c2.reader(io.open(enp, encoding='latin1'), delimiter=';')
    next(rd, None)
    for r in rd:
        if len(r) < 5:
            continue
        key = r[4].strip()
        if key not in FIX:
            continue
        de = FIX[key]
        dnb = len(de.encode('latin1'))
        enb = len(r[4].encode('latin1'))
        if dnb > enb:
            over += 1
            continue
        # skip rows already covered by the batch-1 file
        b1 = '_work/menu_de/%s_de2.csv' % name
        if key.encode('latin1') not in open(b1, 'rb').read():
            pass
        else:
            skip += 1
            continue
        rows.append('%s;%s;%s;%d;%s;%s' % (r[0], r[1], r[2], int(r[3]) if r[3].isdigit() else len(r[4]), esc(r[4]), esc(de)))
        total += 1
    io.open(outp, 'w', encoding='latin1', newline='\n').write(
        'file;off;prefix;len;en;de\n' + '\n'.join(rows) + '\n')
print('rows:', total, 'skip-dup:', skip, 'over:', over)
